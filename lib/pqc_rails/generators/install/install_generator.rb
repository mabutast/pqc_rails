# frozen_string_literal: true

require "yaml"
require "rails/generators"
require_relative "../../hybrid_kem"
require_relative "../../key_source"
require_relative "../../session/encryptor"

module PqcRails
  module Generators
    # `rails generate pqc_rails:install` で実行される。
    # config/initializers/pqc_rails.rbを生成し、セッション用とDB用のHybridKemキーペアを
    # 別々に生成してRails credentialsに保存する。
    # 設定済みの鍵は上書きしない。鍵を置き換えると、その鍵で暗号化したデータを復号できなくなるため。
    class InstallGenerator < Rails::Generators::Base
      # credentialsのキーと、同じ鍵を渡す環境変数の組。
      KEY_NAMES = {
        "pqc_session_key" => "PQC_SESSION_KEY",
        "pqc_record_key" => "PQC_RECORD_KEY"
      }.freeze
      MIGRATION_URL = "https://github.com/mabutast/pqc_rails/blob/main/docs/MIGRATION.md"

      source_root File.expand_path("templates", __dir__)

      # 鍵を書けなかった時に、セットアップのスクリプトが成功として先へ進まないようにする。
      def self.exit_on_failure?
        true
      end

      desc "Generates the pqc_rails initializer and any missing PQC session and record keys in Rails credentials."

      def create_initializer
        copy_file "initializer.rb", "config/initializers/pqc_rails.rb", skip: true
      end

      def add_missing_keys_to_credentials
        return if behavior == :revoke

        stored = parse_credentials(credentials.read)
        missing = KEY_NAMES.keys.reject { |key| report_existing_key(key, stored) }
        return if missing.empty?

        unless options[:pretend]
          write_keys(missing)
          say_status :note, "Generated keys are for ML-KEM-768. For another pq_alg_name, see #{MIGRATION_URL}", :yellow
        end
        missing.each { |key| say_status :credentials, "Added #{key} to Rails credentials" }
      end

      private

      # 鍵が環境変数かcredentialsに定義されていればtrueを返し、状態を表示する。
      # 実行時のKeySource.fetchと同じく、空文字の環境変数も定義済みとして扱う。
      def report_existing_key(key, stored)
        env_value = ENV.fetch(KEY_NAMES.fetch(key), nil)
        return false if env_value.nil? && !stored.key?(key) && !stored.key?(key.to_sym)

        problem = key_problem(env_value || stored[key] || stored[key.to_sym])
        if problem
          say_status :warning, "#{key} #{problem}", :red
        else
          say_status :skip, "#{key} is already set", :yellow
        end
        true
      end

      # 鍵の値を含まない説明を返す。問題が無ければnilを返す。
      def key_problem(value)
        return "is empty: set a value or remove it, then run this generator again" if value.to_s.empty?

        keypair = PqcRails::KeySource.decode(value.to_s)
        return if keypair.authentication_key

        "was generated by pqc_rails 0.3.0 or earlier: rotate to a new key (see #{MIGRATION_URL})"
      rescue PqcRails::KeySource::SeedOnlyKeyError
        "looks like a seed-only key: it was kept. Replace it with a pqc_rails key, " \
          "and do not move it to the previous keys"
      rescue StandardError
        "is not a valid pqc_rails key (truncated or corrupted): it was kept. " \
          "Restore the full value from your backup, and do not move it to the previous keys"
      ensure
        PqcRails::SecretBuffer.wipe(keypair&.secret_key, keypair&.authentication_key)
      end

      def parse_credentials(content)
        YAML.safe_load(content, permitted_classes: [Symbol, Date, Time], aliases: true) || {}
      end

      # YAML全体を書き直すとコメントが消えるので、新しい鍵を末尾に追記する。
      def write_keys(keys)
        credentials.change do |tmp_path|
          original = tmp_path.read
          content = original.empty? || original.end_with?("\n") ? original : "#{original}\n"
          additions = keys.to_h { |key| [key, generate_encoded_key] }
          updated = content + additions.to_yaml.delete_prefix("---\n")
          unless appended_safely?(original, updated, additions)
            raise Thor::Error, "could not append keys to Rails credentials without changing existing values. " \
                               "Nothing was written. Add #{keys.join(' and ')} manually (see #{MIGRATION_URL})"
          end

          tmp_path.write(updated)
        end
      end

      # 追記後のYAMLが、既存の値をすべて保ち、新しい鍵だけが増えた内容であることを確かめる。
      def appended_safely?(original, updated, additions)
        parse_credentials(updated) == parse_credentials(original).merge(additions)
      rescue Psych::Exception, TypeError, NoMethodError
        false
      end

      def generate_encoded_key
        keypair = PqcRails::HybridKem.open(PqcRails::Session::Encryptor::DEFAULT_PQ_ALG_NAME, &:generate_keypair)
        PqcRails::KeySource.encode(keypair)
      ensure
        PqcRails::SecretBuffer.wipe(keypair&.secret_key, keypair&.authentication_key)
      end

      def credentials
        Rails.application.credentials
      end
    end
  end
end
